const LANG_KEY = "babouches_lang";
const savedLang = localStorage.getItem(LANG_KEY);
const browserLang = (navigator.language || "fr").toLowerCase();
let currentLang = (savedLang === "fr" || savedLang === "en")
  ? savedLang
  : (browserLang.indexOf("fr") === 0 ? "fr" : "en");

function t(key, vars) {
  let str = (I18N[currentLang] && I18N[currentLang][key]) || I18N.fr[key] || key;
  if (vars) {
    Object.keys(vars).forEach(function (k) {
      str = str.replace(new RegExp("\\{" + k + "\\}", "g"), vars[k]);
    });
  }
  return str;
}

function formatPrice(value) {
  var n = new Intl.NumberFormat(currentLang === "fr" ? "fr-FR" : "en-US").format(value);
  return n + " " + SHOP.currency;
}

function applyTranslations(root) {
  var scope = root || document;
  scope.querySelectorAll("[data-i18n]").forEach(function (el) {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  scope.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
  scope.querySelectorAll("[data-i18n-aria-label]").forEach(function (el) {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria-label")));
  });
  scope.querySelectorAll("[data-i18n-title]").forEach(function (el) {
    el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
  });
  document.documentElement.lang = currentLang;
  document.title = t("meta.title");
  var metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.setAttribute("content", t("meta.description"));
}

function setLanguage(lang) {
  if (lang !== "fr" && lang !== "en") return;
  currentLang = lang;
  localStorage.setItem(LANG_KEY, lang);
  applyTranslations();
  document.querySelectorAll(".lang-btn").forEach(function (btn) {
    var active = btn.getAttribute("data-lang") === lang;
    btn.classList.toggle("is-active", active);
    btn.setAttribute("aria-pressed", active ? "true" : "false");
  });
  document.dispatchEvent(new CustomEvent("languagechange", { detail: { lang: lang } }));
}
